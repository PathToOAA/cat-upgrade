// 워프권 가격: 목표 레벨까지 드는 총 강화비용의 2배로 책정
export function warpPrice(targetLevel: number) {
  const maxTarget = Math.min(targetLevel, MAX_LEVEL);
  let sum = 0;
  for (let lv = 0; lv < maxTarget; lv++) sum += (UPGRADE_COSTS[lv] ?? 0);
  return Math.round(sum * 2);
}

